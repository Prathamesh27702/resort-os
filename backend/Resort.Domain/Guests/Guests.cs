/// <summary>
/// Marks a property holding personal data. The audit trail records that it changed but not its value, so
/// anonymising a guest really removes their data (audit_logs are append-only and can't be scrubbed later).
/// </summary>
[AttributeUsage(AttributeTargets.Property)]
public sealed class PersonalDataAttribute : Attribute;

/// <summary>A guest profile, shared by every property of the organisation. Never deleted: merged or anonymised.</summary>
public class Guest : AuditableEntity, IOrganizationScoped, IVersioned, IAudited
{
    public Guid OrganizationId { get; set; }
    [PersonalData] public string FirstName { get; set; } = default!;
    [PersonalData] public string? LastName { get; set; }
    [PersonalData] public string? Phone { get; set; }
    [PersonalData] public string? Email { get; set; }
    [PersonalData] public DateOnly? DateOfBirth { get; set; }
    public string? Nationality { get; set; }
    public string? CompanyName { get; set; }
    public string? Gstin { get; set; }
    [PersonalData] public string? Notes { get; set; }
    public bool IsVip { get; set; }
    public string Status { get; set; } = GuestStatuses.Active;
    public Guid? MergedIntoId { get; set; }
    public DateTimeOffset? MergedAt { get; set; }
    public DateTimeOffset? AnonymisedAt { get; set; }
    public Guid? AnonymisedBy { get; set; }
    /// <summary>Generated by the database (name, email, company, lower-case); used for search.</summary>
    public string SearchText { get; private set; } = "";
    /// <summary>Generated by the database (digits of the phone); used for search.</summary>
    public string PhoneDigits { get; private set; } = "";
    public uint Version { get; set; }

    public List<GuestAddress> Addresses { get; set; } = [];
    public List<GuestPreference> Preferences { get; set; } = [];

    public bool IsActive => Status == GuestStatuses.Active;
    public string FullName => string.IsNullOrWhiteSpace(LastName) ? FirstName : $"{FirstName} {LastName}";
}

public class GuestAddress : AuditableEntity, IOrganizationScoped, IAudited
