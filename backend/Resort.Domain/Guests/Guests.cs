/// <summary>Pure helpers for guest data: phone normalisation, name keys and ID number handling.</summary>
public static class GuestRules
{
    /// <summary>
    /// Normalises a phone number to E.164 (+&lt;country&gt;&lt;number&gt;). Indian numbers may be typed the local way:
    /// 98200 12345, 098200 12345, 91 98200 12345 or +91-98200-12345 all become +919820012345.
    /// International numbers need a leading + or 00 (e.g. +44 20 7946 0958, 0044 20 7946 0958).
    /// Returns null when the input can't be a phone number.
    /// </summary>
    public static string? NormalizePhone(string? input)
    {
        if (string.IsNullOrWhiteSpace(input)) return null;
        var s = input.Trim();
        foreach (var ch in s)
            if (!(char.IsAsciiDigit(ch) || ch is '+' or ' ' or '-' or '(' or ')' or '.')) return null;
        var plus = s.StartsWith('+');
        if (s.LastIndexOf('+') > 0) return null;
        var digits = new string(s.Where(char.IsAsciiDigit).ToArray());

        string e164;
        if (plus) e164 = digits;
        else if (digits.StartsWith("00", StringComparison.Ordinal)) e164 = digits[2..];
        else if (digits.Length == 10 && digits[0] is >= '6' and <= '9') e164 = "91" + digits;            // Indian mobile
        else if (digits.Length == 11 && digits[0] == '0' && digits[1] is >= '6' and <= '9') e164 = "91" + digits[1..];
        else if (digits.Length == 12 && digits.StartsWith("91", StringComparison.Ordinal) && digits[2] is >= '6' and <= '9') e164 = digits;
        else if (digits.Length == 11 && digits[0] == '0') e164 = "91" + digits[1..];                       // Indian landline with STD code
        else return null;

        if (e164.Length is < 7 or > 15 || e164[0] == '0') return null;
        if (e164.StartsWith("91", StringComparison.Ordinal) && e164.Length != 12) return null;            // India: 10-digit national numbers
        return "+" + e164;
    }

    /// <summary>Lower-case, trimmed email, or null.</summary>
    public static string? NormalizeEmail(string? email) =>
        string.IsNullOrWhiteSpace(email) ? null : email.Trim().ToLowerInvariant();

    /// <summary>Trims and collapses inner whitespace; null for blank input.</summary>
    public static string? Clean(string? s)
    {
        if (string.IsNullOrWhiteSpace(s)) return null;
        var sb = new StringBuilder(s.Length);
        var space = false;
        foreach (var ch in s.Trim())
        {
            if (char.IsWhiteSpace(ch)) { if (!space) sb.Append(' '); space = true; }
            else { sb.Append(ch); space = false; }
        }
        return sb.ToString();
    }

    /// <summary>Case- and accent-insensitive key for comparing names ("Zoë  D'Souza" = "zoe d'souza").</summary>
    public static string NameKey(string? first, string? last)
    {
        var s = $"{first} {last}".Normalize(NormalizationForm.FormD);
        var sb = new StringBuilder(s.Length);
        foreach (var ch in s)
        {
            if (CharUnicodeInfo.GetUnicodeCategory(ch) == UnicodeCategory.NonSpacingMark) continue;
            if (char.IsLetterOrDigit(ch)) sb.Append(char.ToLowerInvariant(ch));
            else if (char.IsWhiteSpace(ch) && sb.Length > 0 && sb[^1] != ' ') sb.Append(' ');
        }
        return sb.ToString().Trim();
    }

    /// <summary>Upper-case letters and digits only: "a1b 2c-3d" → "A1B2C3D". Used before hashing an ID number.</summary>
    public static string NormalizeIdNumber(string number) =>
        new(number.Where(char.IsAsciiLetterOrDigit).Select(char.ToUpperInvariant).ToArray());

    /// <summary>Last four characters of a normalised ID number, for "•••• 1234" display.</summary>
    public static string Last4(string normalized) => normalized.Length <= 4 ? normalized : normalized[^4..];
}
