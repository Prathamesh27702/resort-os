    [PersonalData] public string? State { get; set; }
    public string? StateCode { get; set; }
    [PersonalData] public string? PostalCode { get; set; }
    public string CountryCode { get; set; } = "IN";

    public bool IsEmpty => Line1 is null && Line2 is null && City is null && State is null && StateCode is null && PostalCode is null;
}

/// <summary>An ID document. The number and details are encrypted by the API; the scan is an encrypted blob.</summary>
public class GuestDocument : AuditableEntity, IOrganizationScoped, IAudited
{
    public Guid OrganizationId { get; set; }
    public Guid GuestId { get; set; }
    public string DocumentType { get; set; } = default!;
    [PersonalData] public byte[]? NumberEncrypted { get; set; }
    [PersonalData] public string? NumberLast4 { get; set; }
    [PersonalData] public byte[]? NumberHash { get; set; }
    public string? IssuingCountry { get; set; }
    public DateOnly? ExpiresOn { get; set; }
    [PersonalData] public byte[]? DetailsEncrypted { get; set; }
    public string? StorageKey { get; set; }
    [PersonalData] public string? FileName { get; set; }
    public string? ContentType { get; set; }
    public int? SizeBytes { get; set; }
    public string KeyId { get; set; } = default!;
    public string Status { get; set; } = DocumentStatuses.Active;
    public DateTimeOffset? PurgedAt { get; set; }

    /// <summary>Removes every identifying field. Used by anonymise and (later) the retention job.</summary>
    public void Purge(DateTimeOffset now)
    {
        NumberEncrypted = null;
        NumberLast4 = null;
        NumberHash = null;
        DetailsEncrypted = null;
        StorageKey = null;
        FileName = null;
        ContentType = null;
        SizeBytes = null;
        Status = DocumentStatuses.Purged;
        PurgedAt = now;
    }
}

