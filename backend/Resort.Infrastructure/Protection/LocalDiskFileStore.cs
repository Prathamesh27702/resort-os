using System.Text.RegularExpressions;
using Microsoft.Extensions.Hosting;
using Microsoft.Extensions.Options;
using Resort.Application.Common;

namespace Resort.Infrastructure.Protection;

public sealed class FileStoreOptions
{
    public const string Section = "FileStore";
    /// <summary>Folder for files on local disk. Relative paths are under the API's content root. Never inside a
    /// folder the web server serves. Default: App_Data/files (gitignored).</summary>
    public string Root { get; set; } = "App_Data/files";
}

/// <summary>
/// Development / single-server file store. Callers store only encrypted bytes here (ID scans are encrypted with
/// <see cref="IFieldEncryptor"/> before saving), so a copied folder reveals nothing. Production swaps in cloud blob
/// storage behind the same interface (Sprint 29).
/// </summary>
public sealed partial class LocalDiskFileStore : IFileStore
{
    [GeneratedRegex("^[a-z0-9][a-z0-9/_-]{0,200}$")]
    private static partial Regex SafeKey();

    private readonly string _root;

    public LocalDiskFileStore(IOptions<FileStoreOptions> options, IHostEnvironment env)
    {
        var root = options.Value.Root;
        _root = Path.GetFullPath(Path.IsPathRooted(root) ? root : Path.Combine(env.ContentRootPath, root));
    }

    private string PathFor(string key)
    {
        // Keys are generated by the API (e.g. "guest-documents/<org>/<id>"), but check anyway: no "..", no absolute paths.
        if (!SafeKey().IsMatch(key) || key.Contains("..", StringComparison.Ordinal))
            throw new ArgumentException("Invalid storage key.", nameof(key));
        var full = Path.GetFullPath(Path.Combine(_root, key.Replace('/', Path.DirectorySeparatorChar)));
        if (!full.StartsWith(_root + Path.DirectorySeparatorChar, StringComparison.Ordinal))
            throw new ArgumentException("Invalid storage key.", nameof(key));
        return full;
    }

    public async Task SaveAsync(string key, byte[] content, CancellationToken ct)
    {
        var path = PathFor(key);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        var tmp = path + ".tmp";
        await File.WriteAllBytesAsync(tmp, content, ct);
        File.Move(tmp, path, overwrite: true);
    }

    public async Task<byte[]?> ReadAsync(string key, CancellationToken ct)
    {
        var path = PathFor(key);
        return File.Exists(path) ? await File.ReadAllBytesAsync(path, ct) : null;
    }

    public Task DeleteAsync(string key, CancellationToken ct)
    {
        var path = PathFor(key);
        if (File.Exists(path)) File.Delete(path);
        return Task.CompletedTask;
    }
}
